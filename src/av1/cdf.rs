pub struct CdfContext {
    pub partition_w8: [[u16; 5]; PARTITION_CONTEXTS],
    pub partition_w16: [[u16; 11]; PARTITION_CONTEXTS],
    pub partition_w32: [[u16; 11]; PARTITION_CONTEXTS],
    pub partition_w64: [[u16; 11]; PARTITION_CONTEXTS],
    pub partition_w128: [[u16; 9]; PARTITION_CONTEXTS],
    pub skip: [[u16; 3]; SKIP_CONTEXTS],
    pub intra_frame_y_mode: [[[u16; INTRA_MODES + 1]; INTRA_MODE_CONTEXTS]; INTRA_MODE_CONTEXTS],
    pub y_mode: [[u16; INTRA_MODES + 1]; BLOCK_SIZE_GROUPS],
    pub uv_mode_cfl_not_allowed: [[u16; INTRA_MODES + 1]; INTRA_MODES],
    pub angle_delta: [[u16; 8]; DIRECTIONAL_MODES],
    pub txb_skip: [[[u16; 3]; TXB_SKIP_CONTEXTS]; TX_SIZE_CONTEXTS],
}

impl Default for CdfContext {
    fn default() -> Self {
        Self::new(0)
    }
}

impl CdfContext {
    pub fn new(base_q_idx: u8) -> Self {
        let coeff_q_context = coeff_q_context(base_q_idx);
        Self {
            partition_w8: DEFAULT_PARTITION_W8_CDF,
            partition_w16: DEFAULT_PARTITION_W16_CDF,
            partition_w32: DEFAULT_PARTITION_W32_CDF,
            partition_w64: DEFAULT_PARTITION_W64_CDF,
            partition_w128: DEFAULT_PARTITION_W128_CDF,
            skip: DEFAULT_SKIP_CDF,
            intra_frame_y_mode: DEFAULT_INTRA_FRAME_Y_MODE_CDF,
            y_mode: DEFAULT_Y_MODE_CDF,
            uv_mode_cfl_not_allowed: DEFAULT_UV_MODE_CFL_NOT_ALLOWED_CDF,
            angle_delta: DEFAULT_ANGLE_DELTA_CDF,
            txb_skip: DEFAULT_TXB_SKIP_CDF[coeff_q_context],
        }
    }
}

impl CdfContext {
    pub fn partition_cdf_mut(&mut self, block_width_mi_log2: u8, context: usize) -> &mut [u16] {
        match block_width_mi_log2 {
            1 => &mut self.partition_w8[context],
            2 => &mut self.partition_w16[context],
            3 => &mut self.partition_w32[context],
            4 => &mut self.partition_w64[context],
            _ => &mut self.partition_w128[context],
        }
    }

    pub fn skip_cdf_mut(&mut self, context: usize) -> &mut [u16] {
        &mut self.skip[context]
    }

    pub fn intra_frame_y_mode_cdf_mut(
        &mut self,
        above_mode_context: usize,
        left_mode_context: usize,
    ) -> &mut [u16] {
        &mut self.intra_frame_y_mode[above_mode_context][left_mode_context]
    }

    pub fn y_mode_cdf_mut(&mut self, block_size_group: usize) -> &mut [u16] {
        &mut self.y_mode[block_size_group]
    }

    pub fn uv_mode_cfl_not_allowed_cdf_mut(&mut self, y_mode_symbol: usize) -> &mut [u16] {
        &mut self.uv_mode_cfl_not_allowed[y_mode_symbol]
    }

    pub fn angle_delta_cdf_mut(&mut self, directional_index: usize) -> &mut [u16] {
        &mut self.angle_delta[directional_index]
    }

    pub fn txb_skip_cdf_mut(&mut self, tx_size_context: usize, context: usize) -> &mut [u16] {
        &mut self.txb_skip[tx_size_context][context]
    }
}

pub fn coeff_q_context(base_q_idx: u8) -> usize {
    match base_q_idx {
        0..=20 => 0,
        21..=60 => 1,
        61..=120 => 2,
        _ => 3,
    }
}

